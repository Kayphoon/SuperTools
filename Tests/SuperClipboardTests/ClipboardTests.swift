import AppKit
import Testing
@testable import SuperClipboard
@testable import SuperTools

struct ClipboardTests {
    private func temporaryDirectory() -> URL {
        FileManager.default.temporaryDirectory.appendingPathComponent("supertools-test-\(UUID().uuidString)")
    }

    private func cleanup(_ directory: URL) {
        guard FileManager.default.fileExists(atPath: directory.path) else { return }
        do { try FileManager.default.removeItem(at: directory) }
        catch { Issue.record("Failed to clean owned test directory: \(error)") }
        #expect(!FileManager.default.fileExists(atPath: directory.path))
    }

    private func image(_ seed: Int = 0, width: Int = 512, height: Int = 256) throws -> CGImage {
        let context = try #require(CGContext(data: nil, width: width, height: height,
                                             bitsPerComponent: 8, bytesPerRow: 0,
                                             space: CGColorSpaceCreateDeviceRGB(),
                                             bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(red: CGFloat((seed * 17) % 256) / 255,
                             green: CGFloat((seed * 31 + 77) % 256) / 255,
                             blue: CGFloat((seed * 53 + 179) % 256) / 255,
                             alpha: 1)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        return try #require(context.makeImage())
    }

    @Test func testTextHistoryDeduplicatesAndEvictsLeastRecentAt200() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            for number in 0...200 { store.recordText("row \(number)") }
            store.recordText("row 1")
            #expect(store.entries.count == 200)
            #expect(store.entries.first?.text == "row 1")
            #expect(store.search("row 0").count == 0)
            #expect(!FileManager.default.fileExists(atPath: directory.path))
        }
    }

    @Test func testDefaultImagesKeep25ThumbnailsWithoutCreatingFiles() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            for number in 0...25 { try store.recordImage(image(number)) }
            #expect(store.entries.count == 25)
            #expect(store.entries.allSatisfy { $0.imageURL == nil })
            #expect(store.entries.first?.thumbnail?.width == 128)
            #expect(store.entries.first?.thumbnail?.height == 64)
            #expect(!FileManager.default.fileExists(atPath: directory.path))
        }
    }

    @Test func testExplicitImagePersistenceRestoresMetadataAndCleansOnOptOut() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            try store.setImagePersistenceEnabled(true)
            let id = try #require(try store.recordImage(image()))
            store.attachOCR("Hello 中文", to: id)
            let restored = try ClipboardStore(directory: directory)
            #expect(restored.search("中文").map(\.id) == [id])
            #expect(restored.entries.first?.imageURL != nil)
            try restored.setImagePersistenceEnabled(false)
            #expect(!FileManager.default.fileExists(atPath: directory.path))
            #expect(restored.entries.allSatisfy { $0.imageURL == nil })
        }
    }

    @Test func testSensitivePasteboardsAreIgnoredIncludingMarkersOnAnotherItem() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType"] {
                pasteboard.clearContents()
                let secret = NSPasteboardItem()
                secret.setString("password", forType: .string)
                let metadata = NSPasteboardItem()
                metadata.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
                pasteboard.writeObjects([secret, metadata])
                monitor.poll()
            }
            #expect(store.entries.count == 0)
        }
    }

    @Test func testMonitorDoesNotArchivePreexistingClipboardAndOwnCopiesDoNotDuplicate() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            pasteboard.setString("preexisting", forType: .string)
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            monitor.poll()
            #expect(store.entries.count == 0)
            let id = try monitor.copyImage(image())
            monitor.poll()
            #expect(store.entries.map(\.id) == [try #require(id)])
            #expect(pasteboard.data(forType: .png) != nil)
        }
    }

    @Test func testMonitorArchivesOrdinaryExternalTextAndMovesDuplicatesToFront() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            for text in ["first", "second", "first"] {
                pasteboard.clearContents()
                pasteboard.setString(text, forType: .string)
                monitor.poll()
            }
            #expect(store.entries.compactMap(\.text) == ["first", "second"])
        }
    }

    @Test func testLateOCRCannotResurrectEvictedImageOrChangePasteboard() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let monitor = PasteboardMonitor(store: store, pasteboard: pasteboard)
            let id = try #require(try monitor.copyImage(image()))
            for number in 1...25 { try store.recordImage(image(number)) }
            try monitor.copyText("newer clipboard")
            store.attachOCR("secret result", to: id)
            #expect(store.search("secret result").count == 0)
            #expect(pasteboard.string(forType: .string) == "newer clipboard")
        }
    }

    @Test func testUncachedImageRestoreFailsWithoutMutatingPasteboard() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            let pasteboard = NSPasteboard.withUniqueName()
            defer {
                pasteboard.releaseGlobally()
                cleanup(directory)
            }
            let store = try ClipboardStore(directory: directory)
            let id = try #require(try store.recordImage(image()))
            pasteboard.setString("untouched", forType: .string)
            #expect(throws: (any Error).self) {
                try store.copy(id, to: pasteboard)
            }
            #expect(pasteboard.string(forType: .string) == "untouched")
        }
    }

    @Test func testImageLRUEvictionDeletesOriginalsAndClearRemovesHistory() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            try store.setImagePersistenceEnabled(true)
            let firstID = try #require(try store.recordImage(image()))
            let firstURL = try #require(store.entries.first?.imageURL)
            for number in 1...25 { try store.recordImage(image(number)) }
            #expect(store.entries.count == 25)
            #expect(!store.entries.contains { $0.id == firstID })
            #expect(!FileManager.default.fileExists(atPath: firstURL.path))
            let cache = ImageDiskCache(directory: directory)
            #expect(try cache.bytes() <= 50_000_000)
            try store.clear()
            #expect(store.entries.count == 0)
            #expect(try ClipboardStore(directory: directory).entries.count == 0)
        }
    }

    @Test func testCacheBudgetEvictsActualLargeOriginals() async throws {
        try await MainActor.run {
            let directory = temporaryDirectory()
            defer { cleanup(directory) }
            let store = try ClipboardStore(directory: directory)
            try store.setImagePersistenceEnabled(true)
            let first = try #require(try store.recordImage(image()))
            let path = try #require(store.entries.first?.imageURL)
            // Simulate a previously cached high-entropy PNG's disk cost. The
            // production byte accounting, not compression in a fixture, owns eviction.
            let file = try FileHandle(forWritingTo: path)
            try file.truncate(atOffset: UInt64(43 * 1024 * 1024))
            try file.close()
            try store.recordImage(image(100))
            #expect(!store.entries.contains { $0.id == first })
            #expect(!FileManager.default.fileExists(atPath: path.path))
            #expect(try ImageDiskCache(directory: directory).bytes() <= 50_000_000)
        }
    }

    @Test func testSettingsStoreLoadsDefaultsAndPersistsCustomShortcuts() throws {
        let directory = temporaryDirectory()
        defer { cleanup(directory) }
        let fileURL = directory.appendingPathComponent("settings.json")
        let store = SettingsStore(fileURL: fileURL)
        #expect(try store.load() == NativeSettings())
        let custom = NativeSettings(
            captureShortcut: NativeShortcut(keyCode: 20, modifiers: 768),
            historyShortcut: NativeShortcut(keyCode: 8, modifiers: 2304),
            imagePersistenceEnabled: true
        )
        try store.save(custom)
        #expect(FileManager.default.fileExists(atPath: fileURL.path))
        #expect(try store.load() == custom)
    }
}
