struct ClipboardTests {
    private func temporaryDirectory() -> URL {
        FileManager.default.temporaryDirectory.appendingPathComponent("supertools-test-\(UUID().uuidString)")
    }

    private func cleanup(_ directory: URL) {
        guard FileManager.default.fileExists(atPath: directory.path) else { return }
        do { try FileManager.default.removeItem(at: directory) }
        catch { Issue.record("Failed to clean owned test directory: \(error)") }
        #expect(!FileManager.default.fileExists(atPath: directory.path))
    }

    private func image(_ seed: Int = 0, width: Int = 512, height: Int = 256) throws -> CGImage {
        let context = try #require(CGContext(data: nil, width: width, height: height,
                                             bitsPerComponent: 8, bytesPerRow: 0,
                                             space: CGColorSpaceCreateDeviceRGB(),
                                             bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(red: CGFloat((seed * 17) % 256) / 255,
                             green: CGFloat((seed * 31 + 77) % 256) / 255,
                             blue: CGFloat((seed * 53 + 179) % 256) / 255,
                             alpha: 1)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        return try #require(context.makeImage())
    }

